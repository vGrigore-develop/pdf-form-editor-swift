"""Generate the S7 SVG fixtures that imitate editor exports (written to
Tests/Fixtures/svg/). handwritten.svg and primitives.svg are hand-written.

cubic_only.svg  The reference outline the way Figma/Illustrator often export it:
                absolute coordinates, 4 decimals, every segment a cubic
                (lines as degenerate cubics, one line split in two collinear
                pieces, the semicircle as three 60-degree cubics), and one
                vertex jittered by 0.04 pt off the orthogonal.
                Expected after "Detect lines and arcs": 11 lines + 1 arc.
nonuniform.svg  The reference outline inside scale(1.2, 1): the right end
                becomes half an ellipse, which must import as curves and must
                not be "detected" as a circular arc.
"""

from __future__ import annotations

import math

from common import FIXTURES
from outline import PAGE_H, R_CX, R_CY, R_R, reference_outline

OUT = FIXTURES / "svg"


def f(v: float) -> str:
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def svg_xy(p):  # page (y up) -> SVG user space (y down), 1 unit = 1 pt
    return p[0], PAGE_H - p[1]


def cubic_line(a, b):
    c1 = (a[0] + (b[0] - a[0]) / 3, a[1] + (b[1] - a[1]) / 3)
    c2 = (a[0] + 2 * (b[0] - a[0]) / 3, a[1] + 2 * (b[1] - a[1]) / 3)
    return "C" + " ".join(f(v) for v in (*c1, *c2, *b))


def cubic_only() -> str:
    o = reference_outline()
    pts = [svg_xy(p) for p in o.end_points()]
    pts[3] = (pts[3][0] + 0.04, pts[3][1])  # (60, 460): slightly off-orthogonal
    d = [f"M{f(pts[0][0])} {f(pts[0][1])}"]
    for k in range(1, 12):  # the 11 lines
        a, b = pts[k - 1], pts[k]
        if k == 1:  # top edge in two collinear pieces
            m = ((a[0] + b[0]) / 2, a[1])
            d.append(cubic_line(a, m)); d.append(cubic_line(m, b))
        elif k % 2:
            d.append(cubic_line(a, b))
        else:
            d.append(f"L{f(b[0])} {f(b[1])}")
    # semicircle from (564.5, 50) to (564.5, 545) through the right, as 3 x 60 deg
    a0 = -math.pi / 2
    for i in range(3):
        s, e = a0 + i * math.pi / 3, a0 + (i + 1) * math.pi / 3
        k = 4 / 3 * math.tan((e - s) / 4)
        P = lambda t: (R_CX + R_R * math.cos(t), R_CY + R_R * math.sin(t))  # noqa: E731
        c1 = (R_CX + R_R * (math.cos(s) - k * math.sin(s)), R_CY + R_R * (math.sin(s) + k * math.cos(s)))
        c2 = (R_CX + R_R * (math.cos(e) + k * math.sin(e)), R_CY + R_R * (math.sin(e) - k * math.cos(e)))
        d.append("C" + " ".join(f(v) for v in (*svg_xy(c1), *svg_xy(c2), *svg_xy(P(e)))))
    d.append("Z")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- generated by spikes/make_svg_fixtures.py: cubic-only export of the reference outline -->\n'
        '<svg xmlns="http://www.w3.org/2000/svg" width="842" height="595" viewBox="0 0 842 595" fill="none">\n'
        f'<path id="voucher" d="{" ".join(d)}" fill="#D9D9D9"/>\n'
        "</svg>\n"
    )


def nonuniform() -> str:
    # Inner geometry: reference x mapped by x' = (x + 84.2) / 1.2, so the outer
    # scale(1.2,1) translate(-84.2,0)... brings the straight parts back to the
    # reference while the semicircle becomes a half ellipse (rx = 1.2 * r').
    o = reference_outline()
    tx = lambda x: (x + 84.2) / 1.2  # noqa: E731
    pts = [(tx(p[0]), PAGE_H - p[1]) for p in o.end_points()]
    d = [f"M{f(pts[0][0])} {f(pts[0][1])}"]
    d += [f"L{f(p[0])} {f(p[1])}" for p in pts[1:12]]
    d.append(f"A{f(R_R)} {f(R_R)} 0 0 0 {f(pts[12][0])} {f(pts[12][1])} Z")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- generated by spikes/make_svg_fixtures.py: non-uniformly scaled reference outline -->\n'
        '<svg xmlns="http://www.w3.org/2000/svg" width="842" height="595" viewBox="0 0 842 595">\n'
        f'<g transform="translate(-84.2 0) scale(1.2 1)"><path id="voucher" d="{" ".join(d)}"/></g>\n'
        "</svg>\n"
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "cubic_only.svg").write_text(cubic_only())
    (OUT / "nonuniform.svg").write_text(nonuniform())
    print("wrote", OUT / "cubic_only.svg", OUT / "nonuniform.svg")


if __name__ == "__main__":
    main()
